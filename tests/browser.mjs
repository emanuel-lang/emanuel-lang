import { chromium } from '@playwright/test';
import { createApp } from '../server/index.js';
import { addUser } from '../server/auth.js';
import { mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import assert from 'node:assert/strict';

process.env.NODE_ENV='production';
const dir=mkdtempSync(join(tmpdir(),'sigeia-browser-'));
const app=await createApp({dataDir:dir,mode:'demo'});
app.server.listen(0,'127.0.0.1');await once(app.server,'listening');
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||(existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined),headless:true,args:['--no-sandbox']});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  page.on('pageerror',error=>{errors.push(error.message);console.error(error.stack);});
  // Tests remain independent of third-party map availability.
  await page.route('https://tile.openstreetmap.org/**',route=>route.abort());
  await page.goto(`http://127.0.0.1:${app.server.address().port}`);
  await page.getByRole('heading',{name:'Tu territorio, en perspectiva.'}).waitFor();
  assert.equal(await page.locator('.metric-value').nth(2).innerText(),'8');
  assert.ok(await page.locator('.leaflet-overlay-pane path').count()>=15);
  assert.equal(await page.locator('i[data-lucide]').count(),0);
  await page.screenshot({path:'/tmp/sigeia-dashboard.png',fullPage:true});
  await page.getByRole('button',{name:'Nuevo territorio'}).click();
  await page.locator('[name="name"]').fill('Territorio de prueba');
  await page.locator('[name="code"]').fill('TEST-01');
  await page.locator('[name="regionId"]').selectOption('r1');
  await page.getByRole('button',{name:'Guardar registro'}).click();
  await page.getByRole('dialog').waitFor({state:'detached'});
  assert.equal(await page.locator('.metric-value').first().innerText(),'4');
  await page.locator('nav').getByRole('link',{name:'Mapa territorial'}).click();
  await page.locator('#polygon-territory').selectOption({label:'Territorio de prueba'});
  await page.getByRole('button',{name:'Dibujar',exact:true}).click();
  const canvas=page.locator('#territory-map');
  await canvas.click({position:{x:230,y:200}});await canvas.click({position:{x:340,y:200}});await canvas.click({position:{x:340,y:300}});
  console.log('Drawing:',await page.locator('#draw-hint').innerText());
  await page.getByRole('button',{name:'Guardar polígono'}).click();
  await page.getByText('Polígono guardado.',{exact:true}).waitFor();
  const current=await page.evaluate(()=>fetch('/api/data').then(r=>r.json()));
  assert.equal(current.territories.find(x=>x.code==='TEST-01').polygon.length,3);
  await page.locator('nav').getByRole('link',{name:'Ciudadanos',exact:true}).click();
  await page.getByRole('button',{name:'Agregar ciudadano'}).click();
  await page.locator('[name="name"]').fill('Registro de prueba navegador');
  await page.locator('[name="houseId"]').selectOption('h1');
  await page.getByRole('button',{name:'Guardar registro'}).click();
  await page.getByRole('dialog').waitFor({state:'detached'});
  await page.getByRole('textbox',{name:'Buscar registros'}).fill('Registro de prueba navegador');
  assert.equal(await page.locator('#records-table tbody tr').count(),1);
  await page.getByRole('button',{name:'Editar registro'}).click();
  await page.locator('[name="status"]').selectOption('Verificado');
  await page.getByRole('button',{name:'Guardar registro'}).click();
  await page.getByRole('dialog').waitFor({state:'detached'});
  await page.getByRole('textbox',{name:'Buscar registros'}).fill('Registro de prueba navegador');
  assert.equal(await page.locator('#records-table .status').innerText(),'Verificado');
  await page.getByRole('button',{name:'Archivar registro'}).click();
  await page.getByRole('button',{name:'Archivar',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'detached'});
  await page.getByRole('textbox',{name:'Buscar registros'}).fill('Registro de prueba navegador');
  await page.getByText('No hay coincidencias',{exact:true}).waitFor();
  await page.locator('nav').getByRole('link',{name:'Indicadores'}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Exportar resumen'}).click();
  assert.equal((await download).suggestedFilename(),'sigeia-resumen-territorial.csv');
  await page.setViewportSize({width:390,height:844});
  await page.goto(`http://127.0.0.1:${app.server.address().port}/#overview`);
  await page.getByRole('heading',{name:'Tu territorio, en perspectiva.'}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'/tmp/sigeia-mobile.png',fullPage:true});
  console.log('PASS browser: dashboard, create, polygon drawing, edit, search, archive, export, mobile');
  await page.close();
  await new Promise(r=>app.server.close(r));
  const pilotDir=join(dir,'pilot');
  const pilot=await createApp({dataDir:pilotDir,mode:'pilot'});
  const password='Browser-synthetic-test-42!';
  addUser(join(pilotDir,'users.json'),'pilotadmin',password,'admin');
  pilot.server.listen(0,'127.0.0.1');await once(pilot.server,'listening');
  const pilotPage=await browser.newPage({viewport:{width:1440,height:1000}});
  pilotPage.on('pageerror',error=>errors.push(error.message));
  await pilotPage.goto(`http://127.0.0.1:${pilot.server.address().port}`);
  await pilotPage.getByRole('heading',{name:'Todo comienza aquí.'}).waitFor();
  await pilotPage.screenshot({path:'/tmp/sigeia-login.png',fullPage:true});
  await pilotPage.locator('[name="username"]').fill('pilotadmin');
  await pilotPage.locator('[name="password"]').fill(password);
  await pilotPage.getByRole('button',{name:'Entrar a la plataforma'}).click();
  await pilotPage.getByRole('heading',{name:'Tu territorio, en perspectiva.'}).waitFor();
  assert.equal(await pilotPage.locator('.metric-value').first().innerText(),'0');
  await pilotPage.reload();
  await pilotPage.getByRole('heading',{name:'Tu territorio, en perspectiva.'}).waitFor();
  await pilotPage.locator('#account').click();
  await pilotPage.getByRole('heading',{name:'Todo comienza aquí.'}).waitFor();
  await pilotPage.close();
  await new Promise(r=>pilot.server.close(r));
  assert.deepEqual(errors,[]);
  console.log('PASS browser: pilot login, empty dataset, session persistence, logout; no JS errors');
}finally{
  await browser.close();
  if(app.server.listening)await new Promise(r=>app.server.close(r));
  rmSync(dir,{recursive:true,force:true});
}
